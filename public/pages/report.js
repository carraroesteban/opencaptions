const t = T[LANG] || T.en;
document.title = `${t.doc} · OpenCaptions`;
mountNav({ current: 'report', crumbs: [home(), { label: t.doc }] });
$('kicker').textContent = t.doc;
$('print').innerHTML = `${icon('print')}<span>${esc(t.print)}</span>`;
$('csv').innerHTML = `${icon('download')}<span>${esc(t.csv)}</span>`;
$('day').setAttribute('aria-label', t.day);
$('print').onclick = () => print();

await ensureSignedIn();

const num = (n) => new Intl.NumberFormat(LANG).format(n);
const dur = (ms) => { const m = Math.round(ms / 60000); return m < 60 ? `${m} min` : `${Math.floor(m / 60)} h ${String(m % 60).padStart(2, '0')}`; };
const money = (n) => `US$ ${n.toFixed(2)}`;
const dayLabel = (d) => new Date(`${d}T12:00:00`).toLocaleDateString(LANG, { weekday: 'long', day: 'numeric', month: 'long' });

// The headline numbers count up once when they arrive (on screen; a printout or reduced motion shows them as they are).
const still = matchMedia('(prefers-reduced-motion: reduce)').matches;
function countUp(el, to, fmt) {
  if (still || !to) { el.textContent = fmt(to); return; }
  const t0 = performance.now();
  const step = (now) => {
    const k = Math.min(1, (now - t0) / 900);
    el.textContent = fmt(to * (1 - (1 - k) ** 3));
    if (k < 1) requestAnimationFrame(step);
  };
  requestAnimationFrame(step);
}

async function load() {
  const day = new URLSearchParams(location.search).get('day') || '';
  const r = await (await fetch(`/api/report${day ? `?day=${day}` : ''}`)).json();
  $('title').textContent = t.title(r.event);
  $('sub').textContent = t.sub(r.totals.talks, day ? dayLabel(day) : '');
  $('day').innerHTML = `<option value="">${esc(t.allDays)}</option>${r.days.map((d) => `<option value="${d}" ${d === day ? 'selected' : ''}>${esc(dayLabel(d))}</option>`).join('')}`;
  $('day').classList.toggle('hidden', r.days.length < 2 && !day);
  $('csv').href = `/api/report.csv${day ? `?day=${day}` : ''}`;
  const tot = r.totals;
  const tiles = [
    ['doc', t.talks, tot.talks, (v) => num(Math.round(v))], ['clock', t.hours, tot.durationMs / 3600000, (v) => v.toFixed(1)],
    ['chat', t.words, tot.words, (v) => num(Math.round(v))], ['phone', t.peak, tot.peakViewers, (v) => num(Math.round(v))],
    ['eye', t.vh, tot.viewerMinutes / 60, (v) => v.toFixed(1)], ['coin', t.cost, tot.costUsd, money],
  ];
  $('totals').innerHTML = tiles.map(([ic, k]) => `<div class="total"><small>${icon(ic)}${esc(k)}</small><b></b></div>`).join('');
  [...$('totals').querySelectorAll('b')].forEach((b, i) => countUp(b, tiles[i][2], tiles[i][3]));
  const rooms = r.rooms.filter((x) => x.talks.length);
  $('rooms').innerHTML = rooms.length ? rooms.map((room) => {
    const longest = Math.max(...room.talks.map((x) => x.durationMs), 1);
    return `<section class="room rise">
    <h2>${esc(room.name)} <small>${esc(t.room(room.totals.talks, dur(room.totals.durationMs)))}</small></h2>
    <div class="wrap"><table>
      <thead><tr>${t.th.map((h, i) => `<th${i > 1 ? ' class="n"' : ''}>${esc(h)}</th>`).join('')}</tr></thead>
      <tbody>${room.talks.map((x) => `<tr>
        <td><b>${esc(x.title || t.untitled)}</b>${x.current ? ` <span class="chip live"><span class="dot live"></span> ${esc(t.live)}</span>` : ''}<div class="who">${esc([(x.speakers.length ? x.speakers : [x.speaker]).filter(Boolean).join(', '), x.languages.join(', ').toUpperCase()].filter(Boolean).join(' · '))}</div></td>
        <td>${esc(new Date(x.startedAt).toLocaleString(LANG, { weekday: 'short', hour: '2-digit', minute: '2-digit' }))}</td>
        <td class="n"><span class="len">${esc(dur(x.durationMs))}<i aria-hidden="true"><b data-w="${Math.round((x.durationMs / longest) * 100)}"></b></i></span></td><td class="n">${esc(num(x.words))}</td><td class="n">${esc(num(x.peakViewers))}</td>
        <td class="n">${esc(num(x.viewerMinutes))}</td><td class="n">${esc(money(x.costUsd))}</td></tr>`).join('')}</tbody>
    </table></div></section>`;
  }).join('') : `<div class="empty rise"><img src="/art/report.webp" alt="" width="1200" height="900" /><p>${esc(t.none)}</p></div>`;
  // The length bars grow in after they're on the page (a width set in the markup would just appear).
  requestAnimationFrame(() => requestAnimationFrame(() => { for (const b of $('rooms').querySelectorAll('[data-w]')) b.style.width = `${b.dataset.w}%`; }));
  $('foot').textContent = t.foot(new Date(r.generatedAt).toLocaleString(LANG, { dateStyle: 'long', timeStyle: 'short' }));
}
$('day').onchange = () => {
  const u = new URL(location.href);
  if ($('day').value) u.searchParams.set('day', $('day').value); else u.searchParams.delete('day');
  history.replaceState(null, '', u);
  load();
};
load();
