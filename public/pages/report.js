// report.html: the event report (GET /api/report): every talk with its length, words, audience and cost, per room
// and in total. Printable (Save as PDF) and downloadable as CSV for a spreadsheet. Crew or admin.
import { esc } from '/common.js';
import { prefsControls, LANG } from '/i18n.js';
import { ensureSignedIn } from '/signin.js';

const $ = (id) => document.getElementById(id);
$('prefs-slot').append(prefsControls());
document.documentElement.lang = LANG;

const T = {
  es: {
    doc: 'Informe del evento', title: (e) => (e ? `${e}: informe` : 'Informe del evento'), back: '← Panel',
    sub: (n, d) => `${n} ${n === 1 ? 'charla subtitulada' : 'charlas subtituladas'}${d ? ` el ${d}` : ''}.`,
    allDays: 'Todos los días', print: 'Imprimir o guardar PDF', csv: 'Descargar CSV',
    talks: 'Charlas', hours: 'Horas subtituladas', words: 'Palabras', peak: 'Pico de público', vh: 'Horas de lectura', cost: 'Costo de IA',
    langs: 'Idiomas de subtítulos',
    th: ['Charla', 'Inicio', 'Duración', 'Palabras', 'Pico', 'Min. de lectura', 'Costo'],
    untitled: 'Charla sin título', live: 'en curso', none: 'Todavía no hay charlas subtituladas.',
    room: (n, m) => `${n} ${n === 1 ? 'charla' : 'charlas'} · ${m}`,
    foot: (d) => `Generado por OpenCaptions el ${d}. Público = personas con los subtítulos abiertos a la vez; minutos de lectura = la suma de todas ellas. El costo es una estimación de la IA (Gemini); el modo local no tiene costo.`,
  },
  en: {
    doc: 'Event report', title: (e) => (e ? `${e}: report` : 'Event report'), back: '← Dashboard',
    sub: (n, d) => `${n} ${n === 1 ? 'talk' : 'talks'} captioned${d ? ` on ${d}` : ''}.`,
    allDays: 'All days', print: 'Print or save as PDF', csv: 'Download CSV',
    talks: 'Talks', hours: 'Hours captioned', words: 'Words', peak: 'Peak audience', vh: 'Reading hours', cost: 'AI cost',
    langs: 'Caption languages',
    th: ['Talk', 'Start', 'Length', 'Words', 'Peak', 'Reading min', 'Cost'],
    untitled: 'Untitled talk', live: 'in progress', none: 'No talks have been captioned yet.',
    room: (n, m) => `${n} ${n === 1 ? 'talk' : 'talks'} · ${m}`,
    foot: (d) => `Generated by OpenCaptions on ${d}. Audience = people with the captions open at the same time; reading minutes = all of them added up. The cost is an estimate of the AI (Gemini); local mode costs nothing.`,
  },
};
const t = T[LANG] || T.en;
document.title = `${t.doc} · OpenCaptions`;
$('back').textContent = t.back;
$('print').textContent = t.print;
$('csv-btn').textContent = t.csv;
$('print').onclick = () => print();

await ensureSignedIn();

const num = (n) => new Intl.NumberFormat(LANG).format(n);
const dur = (ms) => { const m = Math.round(ms / 60000); return m < 60 ? `${m} min` : `${Math.floor(m / 60)} h ${String(m % 60).padStart(2, '0')}`; };
const money = (n) => `US$ ${n.toFixed(2)}`;
const dayLabel = (d) => new Date(`${d}T12:00:00`).toLocaleDateString(LANG, { weekday: 'long', day: 'numeric', month: 'long' });

async function load() {
  const day = new URLSearchParams(location.search).get('day') || '';
  const r = await (await fetch(`/api/report${day ? `?day=${day}` : ''}`)).json();
  $('title').textContent = t.title(r.event);
  $('sub').textContent = t.sub(r.totals.talks, day ? dayLabel(day) : '');
  $('day').innerHTML = `<option value="">${esc(t.allDays)}</option>${r.days.map((d) => `<option value="${d}" ${d === day ? 'selected' : ''}>${esc(dayLabel(d))}</option>`).join('')}`;
  $('day').classList.toggle('hidden', r.days.length < 2 && !day);
  $('csv').href = `/api/report.csv${day ? `?day=${day}` : ''}`;
  const tot = r.totals;
  $('totals').innerHTML = [
    [t.talks, num(tot.talks)], [t.hours, (tot.durationMs / 3600000).toFixed(1)], [t.words, num(tot.words)],
    [t.peak, num(tot.peakViewers)], [t.vh, (tot.viewerMinutes / 60).toFixed(1)], [t.cost, money(tot.costUsd)],
  ].map(([k, v]) => `<div class="total"><small>${esc(k)}</small><b>${esc(v)}</b></div>`).join('');
  const rooms = r.rooms.filter((x) => x.talks.length);
  $('rooms').innerHTML = rooms.length ? rooms.map((room) => `
    <h2>${esc(room.name)} <small>${esc(t.room(room.totals.talks, dur(room.totals.durationMs)))}</small></h2>
    <div class="wrap"><table>
      <thead><tr>${t.th.map((h, i) => `<th${i > 1 ? ' class="n"' : ''}>${esc(h)}</th>`).join('')}</tr></thead>
      <tbody>${room.talks.map((x) => `<tr>
        <td><b>${esc(x.title || t.untitled)}</b>${x.current ? ` <span class="chip bad">${esc(t.live)}</span>` : ''}<div class="who">${esc((x.speakers.length ? x.speakers : [x.speaker]).filter(Boolean).join(', '))}${x.languages.length ? ` · ${esc(x.languages.join(', ').toUpperCase())}` : ''}</div></td>
        <td>${esc(new Date(x.startedAt).toLocaleString(LANG, { weekday: 'short', hour: '2-digit', minute: '2-digit' }))}</td>
        <td class="n">${esc(dur(x.durationMs))}</td><td class="n">${esc(num(x.words))}</td><td class="n">${esc(num(x.peakViewers))}</td>
        <td class="n">${esc(num(x.viewerMinutes))}</td><td class="n">${esc(money(x.costUsd))}</td></tr>`).join('')}</tbody>
    </table></div>`).join('') : `<p class="empty">${esc(t.none)}</p>`;
  $('foot').textContent = t.foot(new Date(r.generatedAt).toLocaleString(LANG, { dateStyle: 'long', timeStyle: 'short' }));
}
$('day').onchange = () => {
  const u = new URL(location.href);
  if ($('day').value) u.searchParams.set('day', $('day').value); else u.searchParams.delete('day');
  history.replaceState(null, '', u);
  load();
};
load();
